const ids = ['language', 'large-text', 'read-aloud', 'conversation', 'history', 'response', 'question', 'listen', 'choices', 'composer', 'utterance', 'dictate', 'example', 'reopen', 'reset', 'review', 'review-heading', 'location', 'drafts', 'notice', 'photo-input', 'photo-tools', 'photo-preview', 'save-photo'];
const ui = Object.fromEntries(ids.map(id => [id, document.getElementById(id)]));
const state = { lang: 'en', mode: 'new', turns: [], place: null, withoutWard: false, example: 0 };
