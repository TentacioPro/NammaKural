function drawPhoto() {
  const canvas = ui['photo-preview'];
  const context = canvas.getContext('2d');
  context.drawImage(image, 0, 0, canvas.width, canvas.height);
  context.strokeStyle = '#ffda70';
  context.lineWidth = 5;
  context.beginPath();
  context.arc(markedAt.x * canvas.width, markedAt.y * canvas.height, 23, 0, Math.PI * 2);
  context.stroke();
  context.fillStyle = '#18352d';
  context.fillRect(0, canvas.height - 34, canvas.width, 34);
  context.fillStyle = '#fff';
  context.font = '16px sans-serif';
  context.fillText(placeSummary(Complaint.interpret(state).place, 'en'), 12, canvas.height - 12, canvas.width - 24);
}

ui['photo-input'].addEventListener('change', () => {
  const file = ui['photo-input'].files[0];
  if (!file) return;
  const version = ++imageVersion;
  const objectUrl = URL.createObjectURL(file);
  const candidate = new Image();
  candidate.onload = () => {
    URL.revokeObjectURL(objectUrl);
    if (version !== imageVersion) return;
    image = candidate;
    markedAt = { x: 0.5, y: 0.5 };
    const canvas = ui['photo-preview'];
    const scale = Math.min(1, 900 / Math.max(image.naturalWidth, image.naturalHeight));
    canvas.width = Math.max(1, Math.round(scale * image.naturalWidth));
    canvas.height = Math.max(1, Math.round(scale * image.naturalHeight));
    ui['photo-tools'].hidden = false;
    drawPhoto();
  };
  candidate.onerror = () => {
    URL.revokeObjectURL(objectUrl);
    if (version === imageVersion) ui.notice.textContent = copy[state.lang].photoError;
  };
  candidate.src = objectUrl;
});

ui['photo-preview'].addEventListener('click', event => {
  if (!image) return;
  const bounds = event.currentTarget.getBoundingClientRect();
  markedAt = { x: (event.clientX - bounds.left) / bounds.width, y: (event.clientY - bounds.top) / bounds.height };
  drawPhoto();
});
ui['photo-preview'].addEventListener('keydown', event => {
  const offsets = { ArrowLeft: [-0.04, 0], ArrowRight: [0.04, 0], ArrowUp: [0, -0.04], ArrowDown: [0, 0.04] };
  if (!image || !offsets[event.key]) return;
  event.preventDefault();
  const [x, y] = offsets[event.key];
  markedAt = { x: Math.max(0, Math.min(1, markedAt.x + x)), y: Math.max(0, Math.min(1, markedAt.y + y)) };
  drawPhoto();
});
ui['save-photo'].addEventListener('click', () => {
  ui['photo-preview'].toBlob(blob => {
    if (!blob || blob.size >= 1_000_000) {
      ui.notice.textContent = copy[state.lang].exportError;
      return;
    }
    const url = URL.createObjectURL(blob);
    const link = node('a');
    link.download = 'nammakural-marked-photo.jpg';
    link.href = url;
    link.click();
    window.setTimeout(() => URL.revokeObjectURL(url), 2000);
    ui.notice.textContent = copy[state.lang].photoSaved;
  }, 'image/jpeg', 0.8);
});

