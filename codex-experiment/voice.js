function node(tag, text, className) {
  const element = document.createElement(tag);
  if (text) element.textContent = text;
  if (className) element.className = className;
  return element;
}

function button(text, action, className = 'quiet') {
  const element = node('button', text, className);
  element.type = 'button';
  element.addEventListener('click', action);
  return element;
}

function resetComplaint() {
  state.turns = [];
  state.place = null;
  state.withoutWard = false;
  ui.utterance.value = '';
  ui.notice.textContent = '';
  ui['photo-input'].value = '';
  ui['photo-tools'].hidden = true;
  ui['photo-input'].closest('details').open = false;
  imageVersion++;
  image = null;
}

async function copyText(text) {
  const t = copy[state.lang];
  try {
    await navigator.clipboard.writeText(text);
    ui.notice.textContent = t.copied;
  } catch {
    ui.notice.textContent = t.copyError;
  }
}

function placeSummary(place, lang) {
  const t = copy[lang];
  if (!place) return t.noWard;
  const name = lang === 'ta' ? place.ta : place.name;
  const area = place.ward ? `Zone ${place.zone} · Ward ${place.ward} (${t.fixture})` : t.noWard;
  return [name, place.city, area].join(' · ');
}

function localizedDraft(result, matched, lang) {
  const t = copy[lang];
  const issueText = matched.map(issue => issue[lang]).join(', ');
  const subject = state.mode === 'reopen' ? `${t.reopenDraft} ${result.reference}` : issueText;
  const action = state.mode === 'reopen' ? t.askReopen : t.askAction;
  return [subject, placeSummary(result.place, lang), issueText ? `${t.reportedIssue} ${issueText}.` : '', action].filter(Boolean).join('\n');
}

function renderDrafts(result) {
  const t = copy[state.lang];
  ui.location.textContent = result.place ? `${t.reported} · ${placeSummary(result.place, state.lang)}` : t.noWard;
  ui.drafts.replaceChildren();
  for (const draft of Complaint.draftsFor(result, state.mode)) {
    const { agency, matched } = draft;
    const article = node('article', '', 'draft');
    const subject = state.mode === 'reopen' ? `${t.reopenDraft} ${result.reference}` : matched.map(issue => issue[state.lang]).join(', ');
    const en = localizedDraft(result, matched, 'en');
    const ta = localizedDraft(result, matched, 'ta');
    const pairs = [[t.subject, subject], [t.location, placeSummary(result.place, state.lang)], [t.english, en], [t.tamil, ta], [t.original, result.spoken]];
    if (state.mode === 'reopen') pairs.splice(1, 0, [t.referenceField, result.reference]);
    if (agency.remarksLimit) {
      const remarks = `${subject}. ${placeSummary(result.place, state.lang)}. ${result.spoken}`;
      const limited = remarks.length <= agency.remarksLimit ? remarks : `${remarks.slice(0, agency.remarksLimit - 1).trimEnd()}…`;
      pairs.splice(2, 0, [t.remarks, limited]);
    }
    const actions = node('div', '', 'draft-actions');
    actions.append(button(t.copyDraft, () => copyText(`${en}\n\n${ta}\n\n${result.spoken}`)));
    if (agency.url) {
      const link = node('a', t.open);
      link.href = agency.url;
      link.target = '_blank';
      link.rel = 'noopener noreferrer';
      actions.append(link);
    }
    const details = node('details');
    const fields = node('dl');
    for (const [label, value] of pairs) {
      const field = node('dd');
      const copyButton = button(t.copy, () => copyText(value));
      copyButton.setAttribute('aria-label', `${t.copy} · ${label}`);
      field.append(node('span', value), copyButton);
      fields.append(node('dt', label), field);
    }
    details.append(node('summary', t.fields), fields);
    if (agency.alternate || agency.phone) {
      const channels = node('div', '', 'draft-actions');
      if (agency.alternate) {
        const email = agency.alternate.startsWith('mailto:');
        const alternate = node('a', email ? t.email : 'WhatsApp');
        alternate.href = agency.alternate;
        if (!email) {
          alternate.target = '_blank';
          alternate.rel = 'noopener noreferrer';
        }
        channels.append(alternate);
      }
      if (agency.phone) {
        const phone = node('a', `${t.call} ${agency.phone}`);
        phone.href = `tel:${agency.phone}`;
        channels.append(phone);
      }
      details.append(channels);
    }
    article.append(node('h3', agency[state.lang]), node('p', subject), actions, details);
    if (!agency.url) article.append(node('p', t.routeNote, 'tip'));
    ui.drafts.append(article);
  }
}

function speakReply() {
  const speech = window.speechSynthesis;
  const voice = speech?.getVoices().find(item => item.lang.toLowerCase().startsWith(state.lang));
  if (!voice) {
    ui.notice.textContent = copy[state.lang].soundError;
    return;
  }
  const utterance = new SpeechSynthesisUtterance(ui.question.textContent);
  utterance.voice = voice;
  utterance.lang = voice.lang;
  speech.cancel();
  speech.speak(utterance);
}

function render({ focus = false } = {}) {
  const t = copy[state.lang];
  document.documentElement.lang = state.lang;
  for (const label of document.querySelectorAll('[data-copy]')) label.textContent = t[label.dataset.copy];
  ui.language.textContent = state.lang === 'en' ? 'தமிழ்' : 'English';
  ui.language.lang = state.lang === 'en' ? 'ta' : 'en';
  ui.reopen.setAttribute('aria-pressed', String(state.mode === 'reopen'));
  ui.history.replaceChildren(...state.turns.map(turn => node('p', turn, 'turn')));
  ui.choices.replaceChildren();
  ui.utterance.placeholder = state.turns.length ? t.replyPlaceholder : t.tryPlaceholder;
  ui.reset.hidden = !state.turns.length && state.mode === 'new';
  ui.conversation.hidden = !state.turns.length && state.mode === 'new';
  ui.response.hidden = ui.conversation.hidden;
  ui.review.hidden = true;
  ui.composer.hidden = false;
  if (!state.turns.length) {
    ui.question.textContent = state.mode === 'reopen' ? t.reference : '';
    if (focus) ui.utterance.focus();
    if (focus && !ui.response.hidden && ui['read-aloud'].getAttribute('aria-pressed') === 'true') speakReply();
    return;
  }
  const result = Complaint.interpret(state);
  let message = result.step === 'review' ? t.ready : t[result.step];
  if (result.step === 'place') {
    const issueNames = result.matched.map(issue => issue[state.lang]).join(', ');
    if (result.choices.length) {
      const names = result.choices.map(place => state.lang === 'ta' ? place.ta : place.name);
      message = `${t.nearby} ${names.join(', ')}.`;
    }
    message = `${t.heard} · ${issueNames}. ${message}`;
    for (const place of result.choices) {
      ui.choices.append(button(state.lang === 'ta' ? place.ta : place.name, () => {
        state.place = place;
        render({ focus: true });
      }, 'choice'));
    }
    ui.choices.append(button(t.skipWard, () => {
      state.withoutWard = true;
      render({ focus: true });
    }));
  }
  ui.question.textContent = message;
  ui.choices.append(button(t.edit, () => {
    const transcript = state.turns.join('\n');
    resetComplaint();
    ui.utterance.value = transcript;
    render({ focus: true });
  }));
  if (result.step === 'review') {
    ui.composer.hidden = true;
    ui.review.hidden = false;
    renderDrafts(result);
    if (focus) ui['review-heading'].focus();
  } else if (focus) ui.utterance.focus();
  if (focus && ui['read-aloud'].getAttribute('aria-pressed') === 'true') speakReply();
}

function submitTurn(text) {
  if (!text.trim()) {
    ui.notice.textContent = copy[state.lang].empty;
    ui.utterance.focus();
    return;
  }
  ui.notice.textContent = '';
  const reply = text.trim();
  if (state.turns.length && Complaint.interpret(state).step === 'place' &&
      /^(?:continue without (?:a |the )?ward|வார்டு இல்லாமல் தொடரவும்)[.!?]?$/i.test(reply)) {
    state.withoutWard = true;
  } else state.turns.push(reply);
  ui.utterance.value = '';
  render({ focus: true });
}

